def placeholder(img: Image.Image) -> str:
    """A 16 px wide JPEG as a data URI: ~500 bytes, enough for a blurred stand-in."""
    thumb = img.convert("RGB").copy()
    thumb.thumbnail((16, 16), Image.LANCZOS)
    buf = io.BytesIO()
    thumb.save(buf, "JPEG", quality=55, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def average_colour(img: Image.Image) -> str:
    r, g, b = img.convert("RGB").resize((1, 1), Image.BOX).getpixel((0, 0))
    return "#%02X%02X%02X" % (r, g, b)


GENERATED = "// GENERATED by scripts/build_assets.py. Do not edit by hand.\n"


def write_typescript(manifest) -> None:
    root = os.path.normpath(os.path.join(HERE, ".."))

    lines = [GENERATED, "export interface MediaFile {", "  number: number;", "  id: string;",
             "  file: string;", "  supplied: string;", "  width: number;", "  height: number;",
             "  average?: string;", "  placeholder?: string;", "}", "",
             "export const mediaFiles: MediaFile[] = ["]
    for e in manifest:
        fields = ["number: %d" % e["number"], "id: %s" % json.dumps(e["id"]),
                  "file: %s" % json.dumps(e["file"]), "supplied: %s" % json.dumps(e["supplied"]),
                  "width: %d" % e["width"], "height: %d" % e["height"]]
        if "average" in e:
            fields.append("average: %s" % json.dumps(e["average"]))
            fields.append("placeholder:\n      %s" % json.dumps(e["placeholder"]))
        lines.append("  {\n    " + ",\n    ".join(fields) + ",\n  },")
    lines.append("];")
    path = os.path.join(root, "packages", "adapters", "src", "seed", "media.generated.ts")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    lines = [GENERATED,
             "// Metro resolves each require() to a bundled asset on iOS, Android and web.",
             "/* eslint-disable @typescript-eslint/no-require-imports */",
             "export const mediaSources = {"]
    for e in manifest:
        key = e["id"] if e["id"].isidentifier() else json.dumps(e["id"]).replace('"', "'")
        lines.append("  %s: require('../../../../assets/reference/%s')," % (key, e["file"]))
    lines.append("} as const;")
    lines.append("")
    lines.append("export type MediaId = keyof typeof mediaSources;")
    path = os.path.join(root, "apps", "mobile", "src", "media", "sources.generated.ts")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main(src: str) -> None:
    os.makedirs(OUT, exist_ok=True)
    manifest = []
    for number, supplied, slug, copy_original in ASSETS:
        path = os.path.join(src, supplied)
        if not os.path.exists(path):
            sys.exit("missing supplied file: " + path)
        img = Image.open(path)
        img.load()
        ext = os.path.splitext(supplied)[1] if copy_original else ".jpg"
        name = "%02d-%s%s" % (number, slug, ext)
        dest = os.path.join(OUT, name)
        if copy_original:
            shutil.copyfile(path, dest)
        else:
            img.convert("RGB").save(dest, "JPEG", quality=86, optimize=True, progressive=True)
        entry = {
            "number": number,
            "id": slug,
            "file": name,
            "supplied": supplied,
            "width": img.width,
            "height": img.height,
            "bytes": os.path.getsize(dest),
        }
        if not copy_original:
            entry["average"] = average_colour(img)
            entry["placeholder"] = placeholder(img)
        manifest.append(entry)
    with open(os.path.join(OUT, "manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")
    write_typescript(manifest)
    total = sum(e["bytes"] for e in manifest)
    print("%d assets, %.1f MB -> %s" % (len(manifest), total / 1e6, OUT))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
