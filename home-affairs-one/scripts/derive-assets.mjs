#!/usr/bin/env node
/**
 * Builds everything the app needs from the 60 photographic masters.
 *
 *   assets/masters/IMG_xxxx.png   the supplied files, never modified
 *   assets/manifest.json          hand-edited: alt text, focal point, placement, review
 *
 * Outputs
 *   apps/web/public/assets/home-affairs-one/A01-360.webp ...   responsive derivatives (git-ignored)
 *   apps/web/src/generated/asset-manifest.json                 manifest + dimensions, checksum, colour
 *   docs/design/asset-manifest.md                              the human-readable register
 *
 * Re-running is cheap: a derivative is only re-encoded when it is missing or
 * older than its master.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const mastersDir = path.join(root, 'assets', 'masters');
const outDir = path.join(root, 'apps', 'web', 'public', 'assets', 'home-affairs-one');
const generatedFile = path.join(root, 'apps', 'web', 'src', 'generated', 'asset-manifest.json');
const docFile = path.join(root, 'docs', 'design', 'asset-manifest.md');

/** Target widths in CSS pixels; the native width is always included. */
const TARGET_WIDTHS = [360, 640, 960];
const QUALITY = 76;

const manifest = JSON.parse(readFileSync(path.join(root, 'assets', 'manifest.json'), 'utf8'));
mkdirSync(outDir, { recursive: true });
mkdirSync(path.dirname(generatedFile), { recursive: true });
mkdirSync(path.dirname(docFile), { recursive: true });

function widthsFor(native) {
  // Drop a target that is within 12% of the native width: it saves nothing.
  const smaller = TARGET_WIDTHS.filter((w) => w < native * 0.88);
  return [...smaller, native];
}

const toHex = ({ r, g, b }) =>
  `#${[r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')}`;

let encoded = 0;
const assets = [];
for (const entry of manifest.assets) {
  const masterPath = path.join(mastersDir, entry.source);
  if (!existsSync(masterPath)) throw new Error(`Missing master for ${entry.id}: ${entry.source}`);
  const bytes = readFileSync(masterPath);
  const image = sharp(bytes);
  const meta = await image.metadata();
  const stats = await image.stats();
  const widths = widthsFor(meta.width);
  const masterTime = statSync(masterPath).mtimeMs;

  for (const width of widths) {
    const target = path.join(outDir, `${entry.id}-${width}.webp`);
    if (existsSync(target) && statSync(target).mtimeMs >= masterTime) continue;
    await sharp(bytes)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: QUALITY, effort: 5 })
      .toFile(target);
    encoded += 1;
  }

  assets.push({
    ...entry,
    width: meta.width,
    height: meta.height,
    bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    color: toHex(stats.dominant),
    widths,
  });
}

writeFileSync(
  generatedFile,
  `${JSON.stringify({ note: 'Generated by scripts/derive-assets.mjs. Do not edit by hand.', assets }, null, 2)}\n`,
);

const cell = (text) => String(text).replace(/\|/g, '\\|');
const rows = assets.map((a) => {
  const review = a.review === 'ok' ? 'Concept use' : '**Needs review**';
  const note = a.reviewNote ? ` — ${a.reviewNote}` : '';
  return `| ${a.id} | \`${a.source}\` | ${a.width} × ${a.height} | ${cell(a.subject)} | ${a.placements
    .map((p) => `\`${p}\``)
    .join(', ')} | ${review}${cell(note)} | ${cell(a.alt)} | \`${a.sha256.slice(0, 12)}\` |`;
});
writeFileSync(
  docFile,
  `# Visual asset manifest

Generated by \`scripts/derive-assets.mjs\` from \`assets/manifest.json\`. Edit the JSON, not this file.

The 60 photographs are illustrative, AI-generated concept assets. They do not show real Home
Affairs offices, staff, citizens, cases or documents. Screens and documents inside the photographs
are decoration only; every label, status and message in the product is rendered by the app.

- **Masters:** \`assets/masters/\`, byte-for-byte as supplied and named by their upload filename.
  \`npm run assets:check\` fails if any master's checksum changes.
- **Derivatives:** WebP at responsive widths in \`apps/web/public/assets/home-affairs-one/\`,
  rebuilt by \`npm run assets:derive\`.
- **Placement** is the screen key where the image is used. **Focal point** (in the JSON) keeps the
  subject in frame when the image is cropped for small screens.
- **Review:** "Concept use" means suitable for this prototype. "Needs review" marks an image that
  conflicts with a rule in the brief and must be checked or replaced before any public release.

| ID | Source file | Pixels | Subject | Placement | Review | Alt text | SHA-256 |
| --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`,
);

const needsReview = assets.filter((a) => a.review !== 'ok').map((a) => a.id);
console.log(
  `assets: ${assets.length} masters, ${encoded} derivative(s) encoded, ` +
    `${needsReview.length} flagged for review${needsReview.length ? ` (${needsReview.join(', ')})` : ''}`,
);
