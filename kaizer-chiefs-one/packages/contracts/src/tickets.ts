import { z } from 'zod';
import { isoDateTime, provenanceSchema } from './provenance';

export const TICKET_STATUSES = ['active', 'used', 'expired', 'transferred', 'cancelled'] as const;
export type TicketStatus = (typeof TICKET_STATUSES)[number];

export const ticketSummarySchema = z.object({
  id: z.string().min(1),
  providerRef: z.string().min(1),
  fixtureId: z.string().nullable(),
  eventName: z.string().min(1),
  eventStart: isoDateTime.nullable(),
  seat: z
    .object({
      gate: z.string().nullable(),
      block: z.string().nullable(),
      row: z.string().nullable(),
      seat: z.string().nullable(),
    })
    .nullable(),
  status: z.enum(TICKET_STATUSES),
  provenance: provenanceSchema,
});
export type TicketSummary = z.infer<typeof ticketSummarySchema>;

/**
 * Entry tokens are short-lived and come only from the ticketing provider at
 * the moment of display. They are never stored in the database, logs or
 * analytics, and never generated by this app.
 */
export const MAX_TICKET_TOKEN_TTL_SECONDS = 300;

export const secureTicketSchema = z
  .object({
    ticketId: z.string().min(1),
    token: z.string().min(16),
    format: z.enum(['qr', 'barcode', 'nfc']),
    issuedAt: isoDateTime,
    expiresAt: isoDateTime,
  })
  .refine(
    (t) => {
      const ttl = (new Date(t.expiresAt).getTime() - new Date(t.issuedAt).getTime()) / 1000;
      return ttl > 0 && ttl <= MAX_TICKET_TOKEN_TTL_SECONDS;
    },
    { message: `Entry tokens must expire within ${MAX_TICKET_TOKEN_TTL_SECONDS}s of issue.` },
  );
export type SecureTicket = z.infer<typeof secureTicketSchema>;

/** A token may be rendered only while unexpired, with a little clock-skew margin. */
export function isTicketTokenUsable(t: SecureTicket, now: Date, skewMs = 5_000): boolean {
  return now.getTime() + skewMs < new Date(t.expiresAt).getTime();
}
