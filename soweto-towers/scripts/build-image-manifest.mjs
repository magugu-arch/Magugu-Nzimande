#!/usr/bin/env node
/**
 * Reads every master in public/images/ and writes src/content/images.generated.ts:
 * intrinsic size and a tiny blur placeholder per image. Alt text and focal
 * points live in src/content/images.ts, keyed by the same slug.
 *
 *   npm run assets:manifest
 */
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'public', 'images');
const files = (await readdir(dir)).filter((f) => f.endsWith('.jpg')).sort();

const entries = [];
for (const file of files) {
  const slug = file.replace(/\.jpg$/, '');
  const img = sharp(path.join(dir, file));
  const { width, height } = await img.metadata();
  const blur = await img.clone().resize(16, 16, { fit: 'inside' }).modulate({ saturation: 1.15 }).jpeg({ quality: 50 }).toBuffer();
  entries.push(
    `  '${slug}': { src: '/images/${file}', width: ${width}, height: ${height}, blurDataURL: 'data:image/jpeg;base64,${blur.toString('base64')}' },`,
  );
}

const out = `// GENERATED by scripts/build-image-manifest.mjs — do not edit by hand.
// Run \`npm run assets:manifest\` after adding or replacing a file in public/images/.

export const imageFiles = {
${entries.join('\n')}
} as const;

export type ImageSlug = keyof typeof imageFiles;
`;

await writeFile(path.join(root, 'src', 'content', 'images.generated.ts'), out);
console.log(`Wrote ${files.length} images to src/content/images.generated.ts`);
