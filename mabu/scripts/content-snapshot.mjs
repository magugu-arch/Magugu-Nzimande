/**
 * Writes the public content the web build renders into its HTML.
 *
 * Search engines (and a guest on a slow connection) should see the menu, the
 * events and the venue in the page itself, not an empty shell that fills in
 * after JavaScript runs. This runs the real handlers against the seeded
 * database and saves their answers to src/content/snapshot.generated.ts,
 * which the app uses as the first paint for public content only; the app then
 * refetches from the API and replaces it.
 *
 *   npm run content:snapshot        (runs before every web export)
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';
import { root } from './lib/web.mjs';

const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'mabu-snapshot-')), 'domain.mjs');
await build({
  stdin: {
    contents: `export { createBackend, seedConfiguration } from './src/domain/backend';
export { createHandlers } from './src/domain/rpc';`,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile: out,
  logLevel: 'error',
});
const { createBackend, seedConfiguration, createHandlers } = await import(pathToFileURL(out).href);

const backend = createBackend({ mode: 'mock' });
seedConfiguration(backend);
const handlers = createHandlers(backend);

/** Public content only: nothing here depends on who is signed in. */
const calls = [
  ['content.home', undefined],
  ['content.menu', undefined],
  ['content.venue', undefined],
  ['booking.policy', undefined],
  ['events.list', undefined],
];
for (const d of backend.db.dishes.list()) calls.push(['content.dish', { id: d.id }]);
for (const w of backend.db.wines.list()) calls.push(['content.wine', { id: w.id }]);
for (const c of backend.db.collections.list()) calls.push(['content.collection', { id: c.id }]);
for (const e of backend.db.experiences.list().filter((x) => x.published))
  calls.push(['events.get', { id: e.id }]);

const snapshot = {};
for (const [name, args] of calls) {
  snapshot[`${name}|${args ? JSON.stringify(args) : ''}`] = await handlers[name](null, args);
}

const file = path.join(root, 'src/content/snapshot.generated.ts');
fs.writeFileSync(
  file,
  `// GENERATED by scripts/content-snapshot.mjs — do not edit. Run \`npm run content:snapshot\`.
//
// The public content the web build renders into its HTML, so a page carries
// its menu and events before JavaScript runs. The app refetches and replaces
// it on load, so the live app is never limited to what is here.

export const contentSnapshot: Record<string, unknown> = ${JSON.stringify(snapshot, null, 2)};

/** The key a query uses to find its snapshot: the call name and its arguments. */
export function snapshotKey(name: string, args: unknown): string {
  return \`\${name}|\${args === undefined || args === null ? '' : JSON.stringify(args)}\`;
}
`,
);
const kb = (fs.statSync(file).size / 1024).toFixed(0);
console.log(`snapshot ${calls.length} public responses (${kb} KB)`);
